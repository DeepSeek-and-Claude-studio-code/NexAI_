    private val enNexRegex = Regex("\\bNex(?!i| Atom| Quark| Sel| Foton| Code)\\b")
    private val ruNexRegex = Regex("Некс(?!и)(?:а|у|ом|е)?")

    fun t(key: String, lang: String, female: Boolean): String {
        val raw = if (lang == "en") enMap[key] ?: ruMap[key] ?: key else ruMap[key] ?: key
        return adaptName(raw, lang, female)
    }

    fun agentName(lang: String, female: Boolean): String = when {
        lang == "en" && female -> "Nexi"
        lang == "en" -> "Nex"
        female -> "Некси"
        else -> "Некс"
    }

    fun adaptName(text: String, lang: String, female: Boolean): String {
        if (!female) return text
        return if (lang == "en") {
            enNexRegex.replace(text, "Nexi")
        } else {
            ruNexRegex.replace(text, "Некси")
                .replace("Готов к работе", "Готова к работе")
                .replace("ваш помощник", "ваша помощница")
        }
    }
